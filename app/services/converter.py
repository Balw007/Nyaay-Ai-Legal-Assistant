"""Section converter: IPC to BNS, CrPC to BNSS, Evidence Act to BSA, and back.

The table in app/data/ipc_bns.json is copied from the Ministry of Home Affairs comparison summaries. It is a
reference for finding the new section quickly, never a substitute for reading the new text: clauses were split,
merged and reworded, so a matching number does not always mean the same rule. Nothing here is generated by AI.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache

from ..config import DATA_DIR

ALIASES = {
    "IPC": ["ipc", "i.p.c", "i.p.c.", "indian penal code", "penal code"],
    "BNS": ["bns", "b.n.s", "bharatiya nyaya sanhita", "nyaya sanhita"],
    "CRPC": ["crpc", "cr.p.c", "cr.p.c.", "cr pc", "code of criminal procedure", "criminal procedure code"],
    "BNSS": ["bnss", "b.n.s.s", "bharatiya nagarik suraksha sanhita", "nagarik suraksha sanhita"],
    "IEA": ["iea", "evidence act", "indian evidence act", "i.e.a"],
    "BSA": ["bsa", "b.s.a", "bharatiya sakshya adhiniyam", "sakshya adhiniyam"],
    "NI": ["ni act", "n.i. act", "n.i act", "negotiable instruments act", "negotiable instrument act", "ni"],
}
SECTION = re.compile(r"(\d{1,4}[A-Za-z]{0,2})((?:\s*\(\s*[A-Za-z0-9]{1,4}\s*\))*)")
FILLER = re.compile(r"\b(u/s|u\.s\.|under|section|sections|sec\.?|s\.|ss\.|of|the|act|code|in|to|for|convert|what|is)\b", re.I)


@lru_cache(maxsize=1)
def table() -> dict:
    return json.loads((DATA_DIR / "ipc_bns.json").read_text(encoding="utf-8"))


def _norm(sec: str) -> str:
    return re.sub(r"\s+", "", sec).upper()


def _base(sec: str) -> str:
    return re.split(r"\(", _norm(sec), maxsplit=1)[0]


def parse_query(q: str) -> dict:
    """'u/s 482 CrPC' -> {act: 'CRPC', section: '482'}.  'section 103(1) BNS' -> {act: 'BNS', section: '103(1)'}."""
    text = " " + (q or "").lower().replace(",", " ") + " "
    act = None
    for key, names in ALIASES.items():
        for n in sorted(names, key=len, reverse=True):
            if re.search(rf"(?<![a-z]){re.escape(n)}(?![a-z])", text):
                act = key
                text = re.sub(rf"(?<![a-z]){re.escape(n)}(?![a-z])", " ", text, count=1)
                break
        if act:
            break
    text = FILLER.sub(" ", text)
    m = SECTION.search(text)
    return {"act": act, "section": _norm(m.group(0)) if m else None}


def _act_info(code: str) -> dict:
    return {"code": code, "name": table()["acts"].get(code, {}).get("name", code)}


def _row(m: dict, matched: str) -> dict:
    t = table()
    return {"matched": matched, "old": {**_act_info(m["old_act"]), "section": m["old"]},
            "new": {**_act_info(m["new_act"]), "section": m["new"]},
            "title": m["title"], "note": m["note"], "tags": m["tags"],
            "source": t["meta"]["sources"].get(m["source"], m["source"])}


def lookup(q: str) -> dict:
    p = parse_query(q)
    t = table()
    out = {"query": q, "parsed": p, "results": [], "omitted": [], "new_provisions": [], "unchanged": [],
           "notice": t["meta"]["notice"]}
    sec = p["section"]
    if not sec:
        out["message"] = "Type a section number with the Act, for example: 302 IPC, 438 CrPC, 65B Evidence Act, 103 BNS."
        return out
    if p["act"] == "NI":
        out["unchanged"] = t["unchanged"]
        out["message"] = f"The Negotiable Instruments Act, 1881 is unchanged. Section {sec} keeps its number."
        return out
    base = _base(sec)
    exact = sec != base  # the user typed a sub-clause such as 103(1)

    def hit(candidate: str) -> bool:
        return _norm(candidate) == sec if exact else _base(candidate) == base

    for m in t["mappings"]:
        if (p["act"] in (None, m["old_act"])) and hit(m["old"]):
            out["results"].append(_row(m, "old"))
        if (p["act"] in (None, m["new_act"])) and hit(m["new"]):
            out["results"].append(_row(m, "new"))
    # a range such as "309(1)-(3)" or "351(2)-(3)" should also be found by its first clause
    if not out["results"] and exact:
        for m in t["mappings"]:
            if (p["act"] in (None, m["new_act"])) and _base(m["new"]) == base and "-" in m["new"]:
                out["results"].append(_row(m, "new"))
    seen, uniq = set(), []
    for r in out["results"]:
        k = (r["old"]["code"], r["old"]["section"], r["new"]["code"], r["new"]["section"], r["matched"])
        if k not in seen:
            seen.add(k)
            uniq.append(r)
    out["results"] = uniq
    for o in t["omitted"]:
        if not exact and (p["act"] in (None, o["old_act"])) and _base(o["old"]) == base:
            out["omitted"].append({**o, "old_act_name": _act_info(o["old_act"])["name"],
                                   "source": t["meta"]["sources"].get(o["source"], o["source"])})
    for n in t["new"]:
        if (p["act"] in (None, n["new_act"])) and (_norm(n["new"]) == sec if exact else _base(n["new"]) == base):
            out["new_provisions"].append({**n, "source": t["meta"]["sources"].get(n["source"], n["source"])})
    if not (out["results"] or out["omitted"] or out["new_provisions"]):
        out["message"] = ("Not in this table. It covers the commonly used sections only. Check the official "
                          "comparison summary or India Code for the rest.")
    return out


def browse(act: str | None = None) -> dict:
    t = table()
    rows = [m for m in t["mappings"] if act in (None, "", m["old_act"], m["new_act"])]
    return {"notice": t["meta"]["notice"], "sources": t["meta"]["sources"], "version": t["meta"]["version"],
            "updated": t["meta"]["updated"], "acts": t["acts"], "count": len(rows),
            "mappings": [_row(m, "old") for m in rows], "omitted": t["omitted"], "new_provisions": t["new"],
            "unchanged": t["unchanged"]}
